const xhttpLink = "vless://a1b2c3d4-e5f6-4a7b-8c9d-0e1f2a3b4c5d@203.0.113.10:443?encryption=none&security=reality&sni=www.microsoft.com&fp=chrome&pbk=Z84J2IelR9ch3k8VtlVhhs5ycBUlXA7wHBWcBrjqnAw&sid=6ba85179e30d4fc2&type=xhttp&path=%2Fxh&mode=auto#HK-XHTTP"

func parsed(t *testing.T, link string) *nodes.Node {
	t.Helper()
	n, err := nodes.ParseLink(link)
	if err != nil {
		t.Fatal(err)
	}
	return n
}

func outboundByTag(t *testing.T, cfg []byte, tag string) map[string]any {
	t.Helper()
	var doc struct {
		Outbounds []map[string]any `json:"outbounds"`
	}
	if err := json.Unmarshal(cfg, &doc); err != nil {
		t.Fatal(err)
	}
	for _, o := range doc.Outbounds {
		if o["tag"] == tag {
			return o
		}
	}
	t.Fatalf("outbound %q missing in %s", tag, cfg)
	return nil
}

func TestXrayNodeBecomesLocalSocks(t *testing.T) {
	n := parsed(t, xhttpLink)
	opts := Options{RouteMode: RouteGlobal, XrayPorts: map[string]xray.Endpoint{xray.Key(n): {Port: 31080}}}
	cfg, err := BuildTUNConfig(n, "warn", opts)
	if err != nil {
		t.Fatal(err)
	}
	ob := outboundByTag(t, cfg, "proxy")
	want := map[string]any{"type": "socks", "tag": "proxy", "server": "127.0.0.1", "server_port": float64(31080), "version": "5"}
	if len(ob) != len(want) {
		t.Fatalf("outbound = %v", ob)
	}
	for k, v := range want {
		if ob[k] != v {
			t.Fatalf("outbound[%s] = %v, want %v (%v)", k, ob[k], v, ob)
		}
	}
	multi, err := BuildConfig(n, 17890, "warn", opts)
	if err != nil || outboundByTag(t, multi, "node-"+n.ID)["type"] != "socks" {
		t.Fatalf("multi config: %v %s", err, multi)
	}
	port, err := BuildPortConfig(PortConfig{Port: 10801, Node: n, XrayPorts: opts.XrayPorts})
	if err != nil || outboundByTag(t, port, "proxy")["server_port"] != float64(31080) {
		t.Fatalf("port config: %v %s", err, port)
	}
}

func TestXrayNodeWithoutSidecar(t *testing.T) {
	n := parsed(t, xhttpLink)
	_, err := BuildTUNConfig(n, "warn", Options{RouteMode: RouteGlobal})
	if !isXrayErr(err) || !strings.Contains(err.Error(), "该节点需要 Xray 内核") {
		t.Fatalf("primary xray node without sidecar: %v", err)
	}
	// As an extra (per-app line) node it must not break the other nodes.
	main := parsed(t, "trojan://pw@example.com:443?sni=example.com#main")
	cfg, err := BuildTUNConfig(main, "warn", Options{RouteMode: RouteGlobal, ExtraNodes: []ExtraNode{{Tag: "line-x", Node: n}}})
	if err != nil {
		t.Fatal(err)
	}
	if ob := outboundByTag(t, cfg, "line-x"); ob["type"] != "socks" || ob["server_port"] != float64(deadXrayPort) {
		t.Fatalf("extra xray node = %v", ob)
	}
}

// Nodes sing-box handles itself are generated byte-identically whatever the
// sidecar state; XrayPath only adds its own direct rule.
func TestNonXrayNodesUnchanged(t *testing.T) {
	x := parsed(t, xhttpLink)
	for _, link := range []string{
		"vless://a1b2c3d4-e5f6-4a7b-8c9d-0e1f2a3b4c5d@203.0.113.13:443?encryption=none&flow=xtls-rprx-vision&security=reality&sni=www.apple.com&fp=chrome&pbk=Z84J2IelR9ch3k8VtlVhhs5ycBUlXA7wHBWcBrjqnAw&sid=01&type=tcp#r",
		"vless://a1b2c3d4-e5f6-4a7b-8c9d-0e1f2a3b4c5d@example.com:443?security=tls&type=ws&path=%2Fws&host=example.com#w",
		"trojan://pw@example.com:443?sni=example.com#t",
		"hysteria2://pw@example.com:443#h",
	} {
		n := parsed(t, link)
		base := Options{RouteMode: RouteBypassCN}
		withPorts := base
		withPorts.XrayPorts = map[string]xray.Endpoint{xray.Key(x): {Port: 31080}}
		a, err1 := BuildTUNConfig(n, "warn", base)
		b, err2 := BuildTUNConfig(n, "warn", withPorts)
		c, err3 := BuildConfig(n, 17890, "warn", base)
		d, err4 := BuildConfig(n, 17890, "warn", withPorts)
		if err1 != nil || err2 != nil || err3 != nil || err4 != nil || !bytes.Equal(a, b) || !bytes.Equal(c, d) {
			t.Fatalf("%s: config changed by sidecar ports", link)
		}
		if strings.Contains(string(a), "xray") {
			t.Fatalf("%s: xray leaked into a plain config", link)
		}
	}
	n := parsed(t, "trojan://pw@example.com:443?sni=example.com#t")
	cfg, err := BuildTUNConfig(n, "warn", Options{RouteMode: RouteGlobal, XrayPath: `C:\ps\bin\xray.exe`})
	if err != nil || !strings.Contains(string(cfg), `"process_path": [`+"\n"+`          "C:\\ps\\bin\\xray.exe"`) {
		t.Fatalf("xray direct rule missing: %v\n%s", err, cfg)
	}
}
